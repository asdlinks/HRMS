function summaryColumns(idField, nameField, nameHeader) {
    return [
        { field: idField, headerName: `${nameHeader} ID` },
        { field: nameField, headerName: nameHeader },
        { field: 'total_count', headerName: 'Total' },
        { field: 'active_count', headerName: 'Active' },
        { field: 'inactive_count', headerName: 'Inactive' },
        { field: 'exited_count', headerName: 'Exited' },
    ];
}

